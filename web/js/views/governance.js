import { api, card, fmt, icon, table, statusTag, esc } from '../ui.js';

export async function render(el) {
  const g = await api.get('/api/governance');
  const p = g.provenance;
  el.innerHTML = `
  <div class="page-head">
    <div><h1>Data &amp; provenance</h1><p>What the forecast is built from, what it is not yet allowed to claim, and who did what. Sources switch on by configuration; when one is absent it is skipped and reported, never imputed.</p></div>
  </div>
  <div class="grid g-2">
    ${card('Source registry', table([
      { h: 'Source', f: (s) => `<b style="font-weight:500">${s.name}</b><div style="font-size:11.5px;color:var(--ink-3)">${s.description}</div>` },
      { h: 'Origin', k: 'origin' },
      { h: 'Status', f: (s) => (s.present ? statusTag('operational') : statusTag('blocked')) },
      { h: 'Unlocks', f: (s) => `<span style="font-size:12px;color:var(--ink-2);white-space:normal">${s.unlocks || '–'}</span>` },
    ], g.sources).html, { flush: true })}
    ${card('Claim control', `
      <div class="kv-row"><span>Study area</span><span>${p.study_area}</span></div>
      <div class="kv-row"><span>Mode</span><span>${statusTag('partial').replace('Partly evidenced', p.mode === 'hindcast' ? 'Hindcast (no NWP feed)' : 'Operational')}</span></div>
      <div class="kv-row"><span>Enabled target</span><span class="mono">${p.enabled_targets.join(', ')}</span></div>
      ${Object.entries(p.blocked_targets).map(([k, v]) => `<div class="kv-row"><span class="mono">${k}</span><span style="text-align:right;max-width:62%;color:var(--warn)">${esc(v)}</span></div>`).join('')}
      <div class="kv-row"><span>Water thresholds</span><span class="mono">VV ≤ ${g.water_thresholds.vv_db_max} dB, VH ≤ ${g.water_thresholds.vh_db_max} dB · ${g.water_thresholds.calibrated ? 'calibrated' : 'prototype, not calibrated'}</span></div>
      <div class="kv-row"><span>Seed</span><span class="mono">${p.seed}</span></div>
      <div class="note" style="margin-top:12px">Products state <b>new surface-water formation</b>. Claims about <i>Anopheles</i> breeding unlock only when RBC larval survey records are connected and Target C is trained on them.</div>`)}
  </div>
  <div class="grid g-2" style="margin-top:14px">
    ${card('Data audit', `<div class="code-block" style="max-height:420px;overflow:auto;white-space:pre-wrap">${esc(g.audit.text || 'No audit report found.')}</div>`, { sub: 'Generated by the study pipeline before every run' })}
    ${g.trail ? card('Audit trail', table([
      { h: 'Time (UTC)', f: (r) => `<span class="mono">${r.ts_utc.replace('T', ' ').replace('Z', '')}</span>` }, { h: 'Actor', f: (r) => esc(r.actor) },
      { h: 'Action', f: (r) => `<span class="mono">${esc(r.action)}</span>` }, { h: 'Detail', f: (r) => `<span style="white-space:normal">${esc(r.detail)}</span>` },
    ], g.trail, { max: 420, empty: 'No activity yet' }).html, { flush: true, sub: 'Append-only; latest 50 entries' }) : card('Audit trail', '<div class="empty sm">Visible to supervisors and administrators.</div>')}
  </div>
  <div class="grid g-3" style="margin-top:14px">
    ${card('Custody and access', `
      <div class="kv-row"><span>Data custody</span><span>African institutional custody (UR-ACEIoT, RBC)</span></div>
      <div class="kv-row"><span>Release terms</span><span>FAIR, open licence after publication</span></div>
      <div class="kv-row"><span>Personal data</span><span>None held; sites are coordinates only</span></div>
      <div class="kv-row"><span>Deployment</span><span>On-premise or national data centre</span></div>
      <div class="kv-row"><span>Identity</span><span>Role workspaces; SSO integration point</span></div>`)}
    ${card('Model registry', Object.entries(g.engine.horizons).map(([h, m]) => `
      <div class="kv-row"><span>${h}-day model</span><span class="mono">${m.fingerprint}</span></div>
      <div class="kv-row"><span style="padding-left:12px">fitted</span><span class="mono">${m.trained_utc}</span></div>`).join('') + `<div class="kv-row"><span>Engine</span><span class="mono">${g.engine.engine_version}</span></div>`)}
    ${card('Interfaces', `
      <div class="kv-row"><span>REST API + OpenAPI</span><a href="/api/docs" target="_blank" rel="noopener">/api/docs</a></div>
      <div class="kv-row"><span>Forecast export</span><span>CSV, GeoJSON</span></div>
      <div class="kv-row"><span>Flight controller</span><span>QGC .plan, MAVLink WPL 110</span></div>
      <div class="kv-row"><span>Field nodes</span><span>HTTPS JSON, per-node key</span></div>
      <div class="kv-row"><span>Onboard logs</span><span>CSV contract, provenance-stamped</span></div>`)}
  </div>`;
}
